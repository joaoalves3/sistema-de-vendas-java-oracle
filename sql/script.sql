-- 3. Consultas usadas nos relatórios -----------------------------------

-- Vendas com o nome do vendedor (INNER JOIN)
SELECT vd.id, v.nome, vd.total, vd.data
FROM java_venda vd
INNER JOIN java_vendedor v ON v.id = vd.id_vendedor
ORDER BY vd.data DESC;

-- Total vendido por vendedor (LEFT JOIN + GROUP BY)
-- Vendedores sem venda aparecem com 0.
SELECT v.nome,
       COUNT(vd.id)              AS qtd,
       COALESCE(SUM(vd.total), 0) AS total
FROM java_vendedor v
LEFT JOIN java_venda vd ON vd.id_vendedor = v.id
GROUP BY v.id, v.nome
ORDER BY total DESC;

-- Vendedores sem nenhuma venda (LEFT JOIN + IS NULL)
SELECT v.id, v.nome
FROM java_vendedor v
LEFT JOIN java_venda vd ON vd.id_vendedor = v.id
WHERE vd.id IS NULL;
